func runLearningResourceScenario(r *Runner, runID string, groupIDs []string, userID string) {
	fields := form(map[string]string{
		"uploaded_user_id": userID, "title": "Modul Regional " + runID,
		"description": "Ditugaskan ke seluruh kelas dan mata pelajaran pada institution target", "type": "link",
		"file_url": "https://example.com/modules/" + runID,
	})
	fields["learning_group_ids"] = groupIDs
	created := r.Form("Learning resource - insert all target groups", http.MethodPost, "/learning-resources", fields, http.StatusCreated)
	id := dataString(created)
	r.JSON("Learning resource - get all", http.MethodGet, "/learning-resources?limit=10", nil, http.StatusOK)
	if id == "" {
		return
	}
	detail := r.JSON("Learning resource - get by ID", http.MethodGet, "/learning-resources/"+id, nil, http.StatusOK)
	assigned := nestedSliceLength(detail, "data", "learning_groups")
	r.Assert("Learning resource - assigned to every class and subject", assigned == len(groupIDs), fmt.Sprintf("expected %d assignments, received %d", len(groupIDs), assigned))
	updateFields := form(map[string]string{"title": "Modul Regional Updated " + runID})
	updateFields["learning_group_ids"] = groupIDs
	r.Form("Learning resource - update", http.MethodPut, "/learning-resources/"+id, updateFields, http.StatusOK)
	r.JSON("Learning resource - archive", http.MethodDelete, "/learning-resources/"+id+"/archived", nil, http.StatusOK)
	r.JSON("Learning resource - delete", http.MethodDelete, "/learning-resources/"+id, nil, http.StatusOK)
}

