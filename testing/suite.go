func runSuite(r *Runner) {
	runID := time.Now().Format("20060102-150405")
	login := r.JSON("Auth - login", http.MethodPost, "/auth/login", map[string]any{
		"email": r.Config.Email, "password": r.Config.Password, "remember_me": true,
	}, http.StatusOK)
	r.Token = nestedString(login, "data", "token")
	ownerID := nestedString(login, "data", "id")
	if r.Token == "" || ownerID == "" {
		r.Skip("Dependent CRUD scenarios", "login failed or response did not contain token/id")
		return
	}

	r.JSON("Roles - master permissions", http.MethodGet, "/roles/master-permissions", nil, http.StatusOK)
	r.JSON("Province - get all", http.MethodGet, "/provinces?limit=100", nil, http.StatusOK)
	r.JSON("Province - get by code", http.MethodGet, "/provinces/"+r.Config.ProvinceCode, nil, http.StatusOK)
	r.JSON("Regency - target region", http.MethodGet, "/regencies?province_code="+r.Config.ProvinceCode+"&limit=500", nil, http.StatusOK)
	r.JSON("Regency - get by code", http.MethodGet, "/regencies/"+r.Config.RegencyCode, nil, http.StatusOK)
	r.JSON("District - get all", http.MethodGet, "/districts?limit=1", nil, http.StatusOK)
	r.JSON("Village - get all", http.MethodGet, "/villages?limit=1", nil, http.StatusOK)

	institution := r.Form("Institution - insert", http.MethodPost, "/institutions", form(map[string]string{
		"name": "API Test School " + runID, "email": "api-test-" + runID + "@example.test",
		"status": "active", "country": "Indonesia", "province_code": r.Config.ProvinceCode,
		"regency_code": r.Config.RegencyCode,
	}), http.StatusCreated)
	institutionID := nestedString(institution, "data", "id")
	if institutionID == "" {
		r.Skip("Learning resource regional scenario", "institution creation failed")
		return
	}
	r.JSON("Institution - get all", http.MethodGet, "/institutions?limit=5", nil, http.StatusOK)
	r.JSON("Institution - get by ID", http.MethodGet, "/institutions/"+institutionID, nil, http.StatusOK)
	r.Form("Institution - update", http.MethodPut, "/institutions/"+institutionID, form(map[string]string{"phone": "081234567890"}), http.StatusOK)

	role := r.JSON("Role - insert", http.MethodPost, "/roles", map[string]any{
		"name": "API Test Role " + runID, "description": "Generated by integration test",
		"permissions": []any{
			map[string]any{"model": "users", "action": "get-all"},
		},
	}, http.StatusCreated)
	roleID := dataString(role)
	r.JSON("Role - get all", http.MethodGet, "/roles?limit=5", nil, http.StatusOK)
	if roleID != "" {
		r.JSON("Role - get by ID", http.MethodGet, "/roles/"+roleID, nil, http.StatusOK)
		r.JSON("Role - update", http.MethodPut, "/roles/"+roleID, map[string]any{"description": "Updated by integration test"}, http.StatusOK)
	}

	var userID string
	if roleID == "" {
		r.Skip("User - insert", "role creation failed")
	} else {
		user := r.Form("User - insert", http.MethodPost, "/users", form(map[string]string{
			"name": "API Test Student", "email": "student-" + runID + "@example.test", "password": "Test12345",
			"pin": "1234", "type": "student", "role_id": roleID, "institution_id": institutionID, "is_active": "active",
		}), http.StatusCreated)
		userID = dataString(user)
	}
	r.JSON("User - get all", http.MethodGet, "/users?limit=5", nil, http.StatusOK)
	if userID != "" {
		r.JSON("User - get by ID", http.MethodGet, "/users/"+userID, nil, http.StatusOK)
		r.JSON("User - get barcode", http.MethodGet, "/users/"+userID+"/barcode", nil, http.StatusOK)
		r.Form("User - update", http.MethodPut, "/users/"+userID, form(map[string]string{"phone": "081200000001"}), http.StatusOK)
	}

	groupIDs := createRegionalLearningGroups(r, runID, institutionID)
	if len(groupIDs) > 0 && userID != "" {
		memberID := runLearningMemberScenario(r, groupIDs[0], userID)
		runLearningResourceScenario(r, runID, groupIDs, userID)
		runQuizScenario(r, runID, institutionID, groupIDs[0], userID)
		runAttendanceScenario(r, institutionID, userID, groupIDs[0])
		if memberID != "" {
			r.JSON("Learning member - archive", http.MethodDelete, "/learning-group-members/"+memberID+"/archived", nil, http.StatusOK)
			r.JSON("Learning member - delete", http.MethodDelete, "/learning-group-members/"+memberID, nil, http.StatusOK)
		}
	} else {
		r.Skip("Learning, quiz, and attendance scenarios", "learning group or user dependency was not created")
	}
	runActivityMasterScenario(r, runID, userID, ownerID)

	for index := len(groupIDs) - 1; index >= 0; index-- {
		id := groupIDs[index]
		r.JSON(fmt.Sprintf("Learning group %d - archive", index+1), http.MethodDelete, "/learning-groups/"+id+"/archived", nil, http.StatusOK)
		r.JSON(fmt.Sprintf("Learning group %d - delete", index+1), http.MethodDelete, "/learning-groups/"+id, nil, http.StatusOK)
	}
	if userID != "" {
		r.JSON("User - archive", http.MethodDelete, "/users/"+userID+"/archived", nil, http.StatusOK)
		r.JSON("User - delete", http.MethodDelete, "/users/"+userID, nil, http.StatusOK)
	}
	if roleID != "" {
		r.JSON("Role - archive", http.MethodDelete, "/roles/"+roleID+"/archived", nil, http.StatusOK)
		r.JSON("Role - delete", http.MethodDelete, "/roles/"+roleID, nil, http.StatusOK)
	}
	r.JSON("Institution - archive", http.MethodDelete, "/institutions/"+institutionID+"/archived", nil, http.StatusOK)
	r.JSON("Institution - delete", http.MethodDelete, "/institutions/"+institutionID, nil, http.StatusOK)
}

func createRegionalLearningGroups(r *Runner, runID, institutionID string) []string {
	levels := []int{1, 2}
	subjects := []string{"Matematika", "IPA"}
	ids := make([]string, 0, len(levels)*len(subjects))
	for _, level := range levels {
		for _, subject := range subjects {
			name := fmt.Sprintf("API Test Kelas %d - %s %s", level, subject, runID)
			response := r.JSON("Learning group - insert "+name, http.MethodPost, "/learning-groups", map[string]any{
				"name": name, "institution_id": institutionID, "code": fmt.Sprintf("T-%s-%d-%s", runID, level, subject),
				"type": "school-class", "level": level, "department": subject, "academic_year": "2026/2027", "is_active": true,
			}, http.StatusCreated)
			if id := dataString(response); id != "" {
				ids = append(ids, id)
			}
		}
	}
	r.JSON("Learning group - get all", http.MethodGet, "/learning-groups?limit=20", nil, http.StatusOK)
	if len(ids) > 0 {
		r.JSON("Learning group - get by ID", http.MethodGet, "/learning-groups/"+ids[0], nil, http.StatusOK)
		r.JSON("Learning group - update", http.MethodPut, "/learning-groups/"+ids[0], map[string]any{"major": "Umum"}, http.StatusOK)
	}
	return ids
}

