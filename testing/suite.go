func form(values map[string]string) map[string][]string {
	result := make(map[string][]string, len(values))
	for key, value := range values {
		result[key] = []string{value}
	}
	return result
}

func nestedSliceLength(response map[string]any, keys ...string) int {
	var current any = response
	for _, key := range keys {
		object, ok := current.(map[string]any)
		if !ok {
			return 0
		}
		current = object[key]
	}
	values, _ := current.([]any)
	return len(values)
}

func nestedFirstString(response map[string]any, keys ...string) string {
	var current any = response
	for _, key := range keys {
		object, ok := current.(map[string]any)
		if !ok {
			return ""
		}
		current = object[key]
	}
	values, ok := current.([]any)
	if !ok || len(values) == 0 {
		return ""
	}
	value, _ := values[0].(string)
	return value
}
